#!/usr/bin/env python3
"""gen-ncvdec-sites.py <dtv_driver_adpt.ko> > ncvdec_sites.h
List the load/store instructions ncvdec patches. The two ref-list writers build their register
addresses arithmetically (0xf0000000 + block), so every store in them is listed and the module
filters by address at run time in LG's MediaTek driver (function + offset +
load/store; no code is copied). Literal pool words are never listed."""
import struct, sys

STORES = """_VDEC_IO_Write32 _VDEC_VLDHWReset _VDEC_ResetVLD1 _VDEC_VLDInitBarrelShifter _VDEC_VLDSetVFifo
_VDEC_SetVldWPtr _VDEC_SetSPSAVLD _VDEC_SetPPSAVLD _VDEC_SetSHDRAVLD1 _VDEC_SetSHDRAVLD2
_VDEC_WriteScalingList _VDEC_AVCReordering _VDEC_PredWeightTable _VDEC_CkgenSel _VDEC_SysClkSel
_VDEC_EnableCRC _VDEC_SetPRefPicListReg _VDEC_SetBRefPicListReg""".split()
LOADS = """_VDEC_IO_Read32 _VDEC_UeCodeNum _VDEC_SeCodeNum _VDEC_AVCReordering _VDEC_PredWeightTable
_VDEC_GetRefAddr""".split()
# The bitstream reader is a static function without a symbol behind this one: only the load
# after "add r0, r0, #0x30000" (the shift-N-bits read at 0xf0030000 + 4*N).
READER = "_VDEC_GetFRateFromSPS"
READER_PAT = (0xe1a00100, 0xe280020f, 0xe2800803, 0xe5900000)

d = open(sys.argv[1], "rb").read()
assert d[:6] == b"\x7fELF\x01\x01", "not a little-endian ELF32"
shoff, = struct.unpack_from("<I", d, 32)
shes, shn, shstr = struct.unpack_from("<HHH", d, 46)
sh = [struct.unpack_from("<10I", d, shoff + i * shes) for i in range(shn)]
def cstr(sec, o):
    b = sh[sec][4] + o
    return d[b:d.index(b"\0", b)].decode()
text = next(i for i, s in enumerate(sh) if cstr(shstr, s[0]) == ".text")
tab = next(s for s in sh if s[1] == 2)
syms, names = {}, {}
for o in range(tab[4], tab[4] + tab[5], 16):
    n, v, sz, info, _, ndx = struct.unpack_from("<IIIBBH", d, o)
    if ndx == text and info & 15 == 2:
        nm = cstr(tab[6], n)
        names[nm] = names.get(nm, 0) + 1
        syms[nm] = (v, sz)
starts = sorted(v for v, _ in syms.values())
W = lambda a: struct.unpack_from("<I", d, sh[text][4] + a)[0]
relocs = set()                                   # words the loader rewrites are never patched
for s in sh:
    if s[1] == 9 and s[7] == text:
        relocs |= {struct.unpack_from("<I", d, o)[0] for o in range(s[4], s[4] + s[5], 8)}

def ok(i):
    rn, rt, rm = i >> 16 & 15, i >> 12 & 15, i & 15
    if i >> 28 == 15 or rn in (13, 15) or rt in (13, 15): return False
    if i & 0x0f600000 == 0x05000000: return True
    return i & 0x0f600ff0 == 0x07000000 and rm not in (13, 15)

def scan(nm, load):
    v, sz = syms[nm]
    lit = {a + 8 + (i & 0xfff) * (1 if i & 0x800000 else -1)
           for a in range(v, v + sz, 4) for i in [W(a)] if i & 0x0f7f0000 == 0x051f0000}
    return [a - v for a in range(v, v + sz, 4)
            if a not in lit and a not in relocs and ok(W(a)) and (W(a) >> 20 & 1) == load]

out = []
for nm in STORES: out += [(nm, o, 0) for o in scan(nm, 0)]
for nm in LOADS:  out += [(nm, o, 1) for o in scan(nm, 1)]
v, _ = syms[READER]
end = next(s for s in starts if s > v)
hit = [a + 12 for a in range(v, end - 12, 4) if tuple(W(a + 4 * k) for k in range(4)) == READER_PAT]
assert len(hit) == 1, hit
out.append((READER, hit[0] - v, 1))
for nm, _, _ in out: assert names[nm] == 1, "ambiguous symbol " + nm

print("/* Generated by gen-ncvdec-sites.py: {function, byte offset, 0 store / 1 load}. Do not edit. */")
for s in out: print('\t{ "%s", 0x%x, %d },' % s)
