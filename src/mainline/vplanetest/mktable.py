#!/usr/bin/env python3
"""mktable.py <warm1> <warm2> <cold>... > mt5398-vplane-path.h
The video path's 720p table for drivers/media/platform/mediatek/mt5398/mt5398-vplane.c, from
tools/vplanerecon.sh snapshots (tv_dump/vplane/): <warm1>/<warm2> a Debian booted while LG's
player showed a 720p clip (the working state, read twice), <cold>... cold Debian boots.
A word goes in when it is the same in both warm reads (not a counter) and differs from at least
one cold boot. Words that read back differently after the writes (status, or control words
whose trigger bits the hardware changes, like 0xf00231b0) stay in: leaving such control words
out (an earlier rule) gave a broken picture, writing them all is what was tested. Pages: 0xf0022000..0xf0025000 (video in,
PDS/regen, deinterlacer, scaler), 0xf0027000 (output stage / mixer), 0xf005e000 (timing),
0xf0036000 (MJC). B2R and CKGEN are programmed by the driver itself."""
import os, sys

def load(f):
    w = {}
    for l in open(f):
        a, rest = l.split(':', 1)
        a = int(a, 16)
        b = rest.split()[:16]
        for i in range(len(b) // 4):
            w.setdefault(a + 4 * i, int(''.join(reversed(b[4 * i:4 * i + 4])), 16))
    return w

w1, w2, *colds = sys.argv[1:]
PAGES = (0xf0022000, 0xf0023000, 0xf0024000, 0xf0025000, 0xf0027000, 0xf005e000, 0xf0036000)
out = []
for pg in PAGES:
    name = '0x%08x.txt' % pg
    A, B = (load(os.path.join(d, name)) for d in (w1, w2))
    C = [load(os.path.join(d, name)) for d in colds if os.path.exists(os.path.join(d, name))]
    for r in sorted(A):
        if A[r] == B.get(r) and any(c.get(r) != A[r] for c in C):
            out.append((r, A[r]))
print('/* SPDX-License-Identifier: GPL-2.0 */')
print('/* Generated by src/mainline/vplanetest/mktable.py from register read-backs of the video path')
print(' * while LG\'s player showed a 720p clip (hardware state, no LG code). Do not edit. */')
print('static const u32 vplane_path_720p[][2] = {')
for r, v in out:
    print('\t{ 0x%08x, 0x%08x },' % (r, v))
print('};')
print('%d words' % len(out), file=sys.stderr)
